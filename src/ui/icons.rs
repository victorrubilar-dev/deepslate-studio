impl Icon {
    /// Filas del dibujo y si va espejado en horizontal.
    fn rows(self) -> (&'static Rows, bool) {
        let rows = match self {
            Icon::Pencil => &PENCIL,
            Icon::Eraser => &ERASER,
            Icon::Fill => &FILL,
            Icon::Picker => &PICKER,
            Icon::Gradient => &GRADIENT,
            Icon::Stamp => &STAMP,
            Icon::Select => &SELECT,
            Icon::Mirror => &MIRROR,
            Icon::Undo | Icon::Redo => &UNDO,
            Icon::New => &NEW,
            Icon::Open => &OPEN,
            Icon::Save => &SAVE,
            Icon::Export => &EXPORT,
            Icon::Close => &CLOSE,
            Icon::Settings => &SETTINGS,
            Icon::Star => &STAR,
            Icon::StarOn => &STAR_ON,
            Icon::Library => &LIBRARY,
            Icon::Flat => &FLAT,
            Icon::Cube => &CUBE,
            Icon::Preview => &PREVIEW,
            Icon::Search => &SEARCH,
            Icon::More => &MORE,
            Icon::Plus => &PLUS,
            Icon::Play => &PLAY,
            Icon::Camera => &CAMERA,
            Icon::Reset => &RESET,
            Icon::Swap => &SWAP,
            Icon::Sun => &SUN,
            Icon::Moon => &MOON,
            Icon::Noise => &NOISE,
            Icon::Split => &SPLIT,
            Icon::Blank => &BLANK,
        };
        (rows, self == Icon::Redo)
    }

    fn raster(self) -> ColorImage {
        let (rows, flip) = self.rows();
        let mut img = ColorImage::filled([SIDE, SIDE], egui::Color32::TRANSPARENT);
        for (y, row) in rows.iter().enumerate() {
            for (x, c) in row.bytes().enumerate() {
                let alpha = match c {
                    b'#' => 255,
                    b'+' => 110,
                    _ => continue,
                };
                let x = if flip { SIDE - 1 - x } else { x };
                img[(x, y)] = egui::Color32::from_white_alpha(alpha);
            }
        }
        img
    }
}

/// Textura del ícono. Se cargan todas la primera vez y quedan en la memoria de egui.
pub fn texture(ctx: &egui::Context, icon: Icon) -> TextureHandle {
    let id = egui::Id::unique("pixel-icons");
    let cached = ctx.data(|d| d.get_temp::<std::sync::Arc<Vec<TextureHandle>>>(id));
    let all = cached.unwrap_or_else(|| {
        let all = std::sync::Arc::new(
            ALL.iter()
                .map(|i| {
                    ctx.load_texture(format!("icon-{i:?}"), i.raster(), TextureOptions::NEAREST)
                })
                .collect::<Vec<_>>(),
        );
        ctx.data_mut(|d| d.insert_temp(id, all.clone()));
        all
    });
    all[ALL.iter().position(|i| *i == icon).unwrap_or(0)].clone()
}

/// Ícono listo para un botón o una etiqueta, al tamaño de diseño (16 puntos).
pub fn image(ctx: &egui::Context, icon: Icon) -> Image<'static> {
    let tex = texture(ctx, icon);
    Image::from_texture((tex.id(), Vec2::splat(SIDE as f32)))
}

