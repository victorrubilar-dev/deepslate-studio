#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_is_16_by_16_with_known_chars() {
        for icon in ALL {
            let (rows, _) = icon.rows();
            for row in rows {
                assert_eq!(row.len(), SIDE, "{icon:?}: {row}");
                assert!(row.bytes().all(|c| b".#+".contains(&c)), "{icon:?}: {row}");
            }
            if icon != Icon::Blank {
                assert!(rows.iter().any(|r| r.contains('#')), "{icon:?} vacío");
            }
        }
    }

    #[test]
    fn redo_is_undo_mirrored() {
        let (u, r) = (Icon::Undo.raster(), Icon::Redo.raster());
        for y in 0..SIDE {
            for x in 0..SIDE {
                assert_eq!(u[(x, y)], r[(SIDE - 1 - x, y)]);
            }
        }
    }
}
